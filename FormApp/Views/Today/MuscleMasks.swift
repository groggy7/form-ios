public extension Workout {
    func bodyViews() -> [BodyView] {
        let muscles = resolvedMuscles
        var remaining = muscles
        var result: [BodyView] = []

        while !remaining.isEmpty {
            guard let first = remaining.first?.views.first else { break }
            result.append(first)
            remaining.removeAll { $0.views.contains(first) }
        }

        if result.isEmpty {
            switch visualRegion {
            case .upper: return [.back]
            case .lower: return [.legsFront]
            case .fullBody: return [.front]
            }
        }
        return result
    }
