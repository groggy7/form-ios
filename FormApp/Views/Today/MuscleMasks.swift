public enum SVGPathParser {
    public static func parse(_ d: String) -> CGPath {
        let path = CGMutablePath()
        let scanner = Scanner(string: d)
        scanner.charactersToBeSkipped = CharacterSet(charactersIn: " ,\t\r\n")
        var currentCmd: Character = " "

        while !scanner.isAtEnd {
            let savedIndex = scanner.currentIndex
            if let ch = scanner.scanCharacter(), "MCLZz".contains(ch) {
                currentCmd = ch
            } else {
                scanner.currentIndex = savedIndex
            }

            switch currentCmd {
            case "M":
                if let x = scanner.scanDouble(), let y = scanner.scanDouble() {
                    path.move(to: CGPoint(x: x, y: y))
                } else { currentCmd = " " }
            case "L":
                if let x = scanner.scanDouble(), let y = scanner.scanDouble() {
                    path.addLine(to: CGPoint(x: x, y: y))
                } else { currentCmd = " " }
            case "C":
                if let x1 = scanner.scanDouble(), let y1 = scanner.scanDouble(),
                   let x2 = scanner.scanDouble(), let y2 = scanner.scanDouble(),
                   let x = scanner.scanDouble(), let y = scanner.scanDouble() {
                    path.addCurve(to: CGPoint(x: x, y: y), control1: CGPoint(x: x1, y: y1), control2: CGPoint(x: x2, y: y2))
                } else { currentCmd = " " }
            case "Z", "z":
                path.closeSubpath()
                currentCmd = " "
            default:
                _ = scanner.scanCharacter()
            }
        }
        return path
    }
}

