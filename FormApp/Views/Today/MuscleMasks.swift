    private static let cacheLock = NSLock()

    public static func paths(for view: BodyView) -> [MuscleGroup: CGPath] {
        cacheLock.lock()
        defer { cacheLock.unlock() }

        if let cached = parsedPathCache[view] {
            return cached
        }

        var result: [MuscleGroup: CGPath] = [:]
        if let rawMap = rawPathStrings[view] {
            for (muscle, pathStr) in rawMap {
                result[muscle] = SVGPathParser.parse(pathStr)
            }
        }

        parsedPathCache[view] = result
        return result
    }
